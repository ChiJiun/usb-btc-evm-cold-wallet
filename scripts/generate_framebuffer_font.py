def _reverse_bits(value: int) -> int:
    value = ((value & 0xF0) >> 4) | ((value & 0x0F) << 4)
    value = ((value & 0xCC) >> 2) | ((value & 0x33) << 2)
    return ((value & 0xAA) >> 1) | ((value & 0x55) << 1)


def build_psf2() -> bytes:
    if len(_UPSTREAM_BASIC) != 128 * 8:
        raise RuntimeError("Pinned upstream glyph table size changed")
    glyphs = bytearray()
    for code in range(256):
        rows = _UPSTREAM_BASIC[code * 8:(code + 1) * 8] if code < 128 else bytes(8)
        for row in rows:
            rendered = _reverse_bits(row)
            glyphs.extend((rendered, rendered))
    header = struct.pack("<8I", PSF2_MAGIC, 0, 32, 0, 256, 16, 16, 8)
    result = header + bytes(glyphs)
    if len(result) != 32 + 256 * 16:
        raise RuntimeError("Generated PSF2 size is inconsistent")
    return result


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_bytes(build_psf2())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
